export interface ValidateResult {
  isValid: boolean;
  errorMessage?: string;
  details?: {
    personTypeCode: string;
    personTypeDescription: string;
    provinceCode: string;
    provinceName: string;
  };
}

/**
 * ฟังก์ชันสำหรับตรวจสอบความถูกต้องของรหัสบัตรประจำตัวประชาชนไทย
 * @param id หมายเลขบัตรประชาชน 13 หลัก (สตริงหรือตัวเลข)
 * @returns อ็อบเจกต์ผลลัพธ์ (ValidateResult)
 */
export function validateThaiID(id: string | number): ValidateResult {
  const idStr = String(id).replace(/-/g, "").trim();

  if (idStr.length !== 13) {
    return { isValid: false, errorMessage: "หมายเลขบัตรประชาชนต้องมี 13 หลัก" };
  }

  if (!/^\d{13}$/.test(idStr)) {
    return { isValid: false, errorMessage: "หมายเลขบัตรประชาชนต้องเป็นตัวเลขเท่านั้น" };
  }

  // Check Modulo 11
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    sum += parseInt(idStr.charAt(i), 10) * (13 - i);
  }
  
  const checkDigit = (11 - (sum % 11)) % 10;
  
  if (checkDigit !== parseInt(idStr.charAt(12), 10)) {
    return { isValid: false, errorMessage: "หมายเลขบัตรประชาชนไม่ถูกต้อง (Check digit ไม่ตรง)" };
  }

  // Parse Details
  const personTypeCode = idStr.charAt(0);
  const provinceCode = idStr.substring(1, 3);
  
  const personTypeDescription = PERSON_TYPES[personTypeCode] || "ประเภทบุคคลไม่ระบุ";
  const provinceName = PROVINCES[provinceCode] || "ไม่ทราบจังหวัด (หรือรหัสเก่า/พิเศษ)";

  return {
    isValid: true,
    details: {
      personTypeCode,
      personTypeDescription,
      provinceCode,
      provinceName
    }
  };
}
